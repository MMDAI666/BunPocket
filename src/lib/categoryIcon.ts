/** 按系统分类 name_key 查图标库图标，查不到返回 null */
export function categoryIcon(
  nameKey: string | null | undefined,
): LucideIcon | null {
  if (!nameKey) return null;
  return CATEGORY_ICONS[nameKey] ?? null;
}
